// Package models defines the core data structures for the application
// Device models support the Signal Protocol for end-to-end encryption
package models

import (
	"time"

	"github.com/google/uuid"
)

// Device represents a user's device in the system
// Each device has its own cryptographic identity and message sessions
// This is essential for Signal Protocol's multi-device support
type Device struct {
	// ID is the unique identifier for the device
	ID uuid.UUID `json:"id" db:"id"`

	// UserID is the ID of the user who owns this device
	UserID uuid.UUID `json:"user_id" db:"user_id"`

	// DeviceID is a unique identifier for this specific device
	// This is generated by the client and used in Signal Protocol
	DeviceID string `json:"device_id" db:"device_id"`

	// Name is a human-readable name for the device (e.g., "iPhone 13", "MacBook Pro")
	Name string `json:"name" db:"name"`

	// IdentityKeyPublic is the public part of the device's identity key
	// In Signal Protocol, this is an Ed25519 public key
	// This key identifies the device long-term
	IdentityKeyPublic []byte `json:"identity_key_public" db:"identity_key_public"`

	// IdentityKeyPrivate is the private part - NEVER STORED ON SERVER!
	// This comment is a reminder that the server should NEVER have access to private keys
	// IdentityKeyPrivate []byte `json:"-" db:"-"` // NOT STORED

	// SignedPrekeyPublic is the public part of the signed prekey
	// This is signed by the identity key and rotated periodically
	SignedPrekeyPublic []byte `json:"signed_prekey_public" db:"signed_prekey_public"`

	// SignedPrekeySignature is the signature of the signed prekey by the identity key
	SignedPrekeySignature []byte `json:"signed_prekey_signature" db:"signed_prekey_signature"`

	// SignedPrekeyID is the ID of the current signed prekey
	SignedPrekeyID uint32 `json:"signed_prekey_id" db:"signed_prekey_id"`

	// OneTimePrekeyID is the starting ID for one-time prekeys
	// One-time prekeys are ephemeral and used only once
	OneTimePrekeyID uint32 `json:"one_time_prekey_id" db:"one_time_prekey_id"`

	// IsActive indicates if this device is currently active
	IsActive bool `json:"is_active" db:"is_active"`

	// IsVerified indicates if this device has been verified by the user
	IsVerified bool `json:"is_verified" db:"is_verified"`

	// CreatedAt is when the device was registered
	CreatedAt time.Time `json:"created_at" db:"created_at"`

	// UpdatedAt is when the device was last updated
	UpdatedAt time.Time `json:"updated_at" db:"updated_at"`

	// LastSeenAt is when the device was last active
	LastSeenAt *time.Time `json:"last_seen_at,omitempty" db:"last_seen_at"`

	// RegistrationID is used in Signal Protocol for initial setup
	// This is a random 16-byte value
	RegistrationID []byte `json:"registration_id" db:"registration_id"`
}

// DeviceCreateRequest is the request body for registering a new device
type DeviceCreateRequest struct {
	// DeviceID is generated by the client
	DeviceID string `json:"device_id" binding:"required"`

	// Name is the device name
	Name string `json:"name" binding:"required,min=1,max=100"`

	// IdentityKeyPublic is the public identity key
	IdentityKeyPublic []byte `json:"identity_key_public" binding:"required"`

	// SignedPrekeyPublic is the current signed prekey
	SignedPrekeyPublic []byte `json:"signed_prekey_public" binding:"required"`

	// SignedPrekeySignature is the signature of the signed prekey
	SignedPrekeySignature []byte `json:"signed_prekey_signature" binding:"required"`

	// SignedPrekeyID is the ID of the signed prekey
	SignedPrekeyID uint32 `json:"signed_prekey_id" binding:"required"`

	// OneTimePrekeyID is the starting ID for one-time prekeys
	OneTimePrekeyID uint32 `json:"one_time_prekey_id"`

	// RegistrationID for Signal Protocol
	RegistrationID []byte `json:"registration_id" binding:"required"`
}

// DeviceResponse is the response when returning device information
type DeviceResponse struct {
	ID                uuid.UUID `json:"id"`
	UserID            uuid.UUID `json:"user_id"`
	DeviceID          string    `json:"device_id"`
	Name              string    `json:"name"`
	IdentityKeyPublic []byte    `json:"identity_key_public"`
	SignedPrekeyPublic []byte    `json:"signed_prekey_public"`
	SignedPrekeyID     uint32   `json:"signed_prekey_id"`
	OneTimePrekeyID    uint32   `json:"one_time_prekey_id"`
	IsActive          bool      `json:"is_active"`
	IsVerified        bool      `json:"is_verified"`
	CreatedAt         time.Time `json:"created_at"`
	UpdatedAt         time.Time `json:"updated_at"`
	LastSeenAt        *time.Time `json:"last_seen_at,omitempty"`
}

// Prekey represents a one-time prekey for a device
// These are used in the X3DH key exchange of Signal Protocol
type Prekey struct {
	// ID is the unique identifier for the prekey
	ID uuid.UUID `json:"id" db:"id"`

	// DeviceID is the device that owns this prekey
	DeviceID uuid.UUID `json:"device_id" db:"device_id"`

	// PrekeyID is the numeric ID of the prekey (assigned by device)
	PrekeyID uint32 `json:"prekey_id" db:"prekey_id"`

	// PublicKey is the public part of the prekey
	PublicKey []byte `json:"public_key" db:"public_key"`

	// IsUsed indicates if this prekey has been used
	// Once used, it should not be used again
	IsUsed bool `json:"is_used" db:"is_used"`

	// CreatedAt is when the prekey was created
	CreatedAt time.Time `json:"created_at" db:"created_at"`
}

// PrekeyBundle is what a client needs to start a Signal Protocol session
type PrekeyBundle struct {
	// DeviceID identifies which device this bundle is for
	DeviceID string `json:"device_id"`

	// IdentityKeyPublic is the device's long-term identity public key
	IdentityKeyPublic []byte `json:"identity_key_public"`

	// SignedPrekeyPublic is the current signed prekey
	SignedPrekeyPublic []byte `json:"signed_prekey_public"`

	// SignedPrekeySignature is the signature of the signed prekey
	SignedPrekeySignature []byte `json:"signed_prekey_signature"`

	// SignedPrekeyID is the ID of the signed prekey
	SignedPrekeyID uint32 `json:"signed_prekey_id"`

	// OneTimePrekey is an available one-time prekey (if exists)
	OneTimePrekey *PrekeyResponse `json:"one_time_prekey,omitempty"`

	// RegistrationID is needed for the initial Signal Protocol handshake
	RegistrationID []byte `json:"registration_id"`
}

// PrekeyResponse is the response format for a prekey
type PrekeyResponse struct {
	PrekeyID  uint32 `json:"prekey_id"`
	PublicKey []byte `json:"public_key"`
}
