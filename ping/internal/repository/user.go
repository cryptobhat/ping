// GetMembership gets a user's membership in a conversation
func (r *UserRepository) GetMembership(ctx context.Context, conversationID, userID uuid.UUID) (*models.Membership, error) {
	const sql = `
		SELECT 
			id, conversation_id, user_id, device_id, role, 
			is_active, joined_at, left_at
		FROM memberships
		WHERE conversation_id = $1 AND user_id = $2
	`

	membership := &models.Membership{}
	err := r.db.QueryRow(ctx, sql, conversationID, userID).Scan(
		&membership.ID,
		&membership.ConversationID,
		&membership.UserID,
		&membership.DeviceID,
		&membership.Role,
		&membership.IsActive,
		&membership.JoinedAt,
		&membership.LeftAt,
	)

	if err != nil {
		if err == pgx.ErrNoRows {
			return nil, fmt.Errorf("membership not found")
		}
		return nil, fmt.Errorf("failed to get membership: %w", err)
	}

	return membership, nil
}

