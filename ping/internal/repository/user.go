// ListConversations lists all conversations for a user
func (r *UserRepository) ListConversations(ctx context.Context, userID uuid.UUID) ([]*models.Conversation, error) {
	const sql = `
		SELECT 
			c.id, c.type, c.creator_id, c.title, c.avatar_url, c.description,
			c.is_encrypted, c.is_archived, c.is_muted, c.muted_until,
			c.created_at, c.updated_at, c.last_message_at, c.last_message_id
		FROM conversations c
		JOIN memberships m ON c.id = m.conversation_id
		WHERE m.user_id = $1 AND m.is_active = TRUE
		ORDER BY c.updated_at DESC
	`

	rows, err := r.db.Query(ctx, sql, userID)
	if err != nil {
		return nil, fmt.Errorf("failed to list conversations: %w", err)
	}
	defer rows.Close()

	var conversations []*models.Conversation
	for rows.Next() {
		conversation := &models.Conversation{}
		err := rows.Scan(
			&conversation.ID,
			&conversation.Type,
			&conversation.CreatorID,
			&conversation.Title,
			&conversation.AvatarURL,
			&conversation.Description,
			&conversation.IsEncrypted,
			&conversation.IsArchived,
			&conversation.IsMuted,
			&conversation.MutedUntil,
			&conversation.CreatedAt,
			&conversation.UpdatedAt,
			&conversation.LastMessageAt,
			&conversation.LastMessageID,
		)
		if err != nil {
			return nil, fmt.Errorf("failed to scan conversation: %w", err)
		}
		conversations = append(conversations, conversation)
	}

	return conversations, nil
}
