// ListByIDs finds multiple users by their IDs
func (r *UserRepository) ListByIDs(ctx context.Context, ids []uuid.UUID) ([]*models.User, error) {
	if len(ids) == 0 {
		return []*models.User{}, nil
	}

	// Build the query with IN clause
	query, args := buildInQuery("SELECT id, username, display_name, email, phone, avatar_url, status, is_active, created_at, updated_at, last_seen_at FROM users WHERE id = ANY($1)", ids)

	rows, err := r.db.Query(ctx, query, args...)
	if err != nil {
		return nil, fmt.Errorf("failed to query users: %w", err)
	}
	defer rows.Close()

	var users []*models.User
	for rows.Next() {
		user := &models.User{}
		err := rows.Scan(
			&user.ID,
			&user.Username,
			&user.DisplayName,
			&user.Email,
			&user.Phone,
			&user.AvatarURL,
			&user.Status,
			&user.IsActive,
			&user.CreatedAt,
			&user.UpdatedAt,
			&user.LastSeenAt,
		)
		if err != nil {
			return nil, fmt.Errorf("failed to scan user: %w", err)
		}
		users = append(users, user)
	}

	return users, nil
}

// SearchByUsername searches for users by username prefix
// This is used for finding contacts
func (r *UserRepository) SearchByUsername(ctx context.Context, prefix string, limit int) ([]*models.User, error) {
	const sql = `
		SELECT 
			id, username, display_name, avatar_url, status
		FROM users
		WHERE username LIKE $1
		ORDER BY username
		LIMIT $2
	`

	searchPattern := prefix + "%"
	rows, err := r.db.Query(ctx, sql, searchPattern, limit)
	if err != nil {
		return nil, fmt.Errorf("failed to search users: %w", err)
	}
	defer rows.Close()

	var users []*models.User
	for rows.Next() {
		user := &models.User{}
		err := rows.Scan(
			&user.ID,
			&user.Username,
			&user.DisplayName,
			&user.AvatarURL,
			&user.Status,
		)
		if err != nil {
			return nil, fmt.Errorf("failed to scan user: %w", err)
		}
		users = append(users, user)
	}

	return users, nil
}

// buildInQuery builds a query with an IN clause for UUIDs
func buildInQuery(baseQuery string, ids []uuid.UUID) (string, []interface{}) {
	args := make([]interface{}, len(ids))
	for i, id := range ids {
		args[i] = id
	}
	return baseQuery, args
}

