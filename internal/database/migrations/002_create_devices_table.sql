-- Description: Creates the devices table for storing user devices
-- This is essential for Signal Protocol multi-device support

CREATE TABLE IF NOT EXISTS devices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id VARCHAR(64) NOT NULL,
    name VARCHAR(100) NOT NULL,
    identity_key_public BYTEA NOT NULL,
    signed_prekey_public BYTEA NOT NULL,
    signed_prekey_signature BYTEA NOT NULL,
    signed_prekey_id INTEGER NOT NULL,
    one_time_prekey_id INTEGER NOT NULL DEFAULT 0,
    registration_id BYTEA NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMP WITH TIME ZONE
);

-- Create unique constraint on user_id + device_id
-- This ensures a user can't register the same device twice
CREATE UNIQUE INDEX IF NOT EXISTS idx_devices_unique_user_device 
    ON devices(user_id, device_id);

-- Create index for faster device lookups by device_id
CREATE INDEX IF NOT EXISTS idx_devices_device_id ON devices(device_id);

-- Create index for user_id to find all devices for a user
CREATE INDEX IF NOT EXISTS idx_devices_user_id ON devices(user_id);

-- Create index for active devices
CREATE INDEX IF NOT EXISTS idx_devices_active ON devices(user_id) WHERE is_active = TRUE;

-- Create trigger to update updated_at
CREATE OR REPLACE FUNCTION update_devices_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_update_devices_updated_at ON devices;
CREATE TRIGGER trigger_update_devices_updated_at
    BEFORE UPDATE ON devices
    FOR EACH ROW
    EXECUTE FUNCTION update_devices_updated_at();

